function loadStoredLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LANGS.includes(saved)) return saved;
  } catch (err) {
    // localStorage nedostupné (např. sandbox) — tichý pád na výchozí jazyk
  }
  return DEFAULT_LANG;
}

let currentLang = loadStoredLang();
const listeners = new Set();

/** Aktuálně zvolený jazyk. */
export function getLang() {
  return currentLang;
}

/** Přepne jazyk (musí být jeden z LANGS), uloží do localStorage a zavolá
 *  všechny zaregistrované posluchače (viz onLangChange). */
export function setLang(code) {
  if (!LANGS.includes(code) || code === currentLang) return;
  currentLang = code;
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch (err) {
    // localStorage nedostupné — jazyk zůstane platný jen pro tuto session
  }
  listeners.forEach((cb) => {
    try {
      cb(currentLang);
    } catch (err) {
      console.error('i18n: chyba v posluchači onLangChange', err);
    }
  });
}

/** Zaregistruje posluchače volaného po každé změně jazyka. Vrací funkci
 *  pro odregistrování. */
export function onLangChange(cb) {
  if (typeof cb !== 'function') return () => {};
  listeners.add(cb);
  return () => listeners.delete(cb);
}

/** Přeloží klíč do aktuálního jazyka. Chybějící překlad spadne na angličtinu,
 *  úplně chybějící klíč (překlep, nový string bez záznamu) vrátí samotný
 *  klíč jako nouzovou zálohu — nikdy nevyhodí chybu. `params` (volitelně)
 *  dosadí {jméno} placeholdery v textu. */
export function t(key, params) {
  const langDict = DICTS[currentLang] || DICTS[DEFAULT_LANG];
  let str = langDict ? langDict[key] : undefined;
  if (str === undefined) {
    str = DICTS[DEFAULT_LANG][key];
  }
  if (str === undefined) {
    return key;
  }
  if (params && typeof params === 'object') {
    Object.keys(params).forEach((name) => {
      str = str.split(`{${name}}`).join(String(params[name]));
    });
  }
  return str;
}

/** Projde element (výchozí celý dokument) a vyplní texty/atributy podle
 *  data-i18n(-*) atributů — pro statické texty v index.html, které se
 *  nemusí přegenerovávat v JS. Volá se při startu a po každé změně jazyka. */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
  root.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.alt = t(el.getAttribute('data-i18n-alt'));
  });
  if (root === document) {
    document.title = t('app.docTitle');
    document.documentElement.lang = currentLang;
  }
}
